"""
TrustMail: Security Assessment Data Models.
Defines structured classes and Enums for findings, dimensions, and evaluation vectors.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class FindingCategory(str, Enum):
    """
    Categorizes the epistemological certainty of each finding.
    Strictly distinguishes established facts from heuristic alerts or unverified claims.
    """
    VERIFIED_FACT = "VERIFIED_FACT"
    UNVERIFIED_CLAIM = "UNVERIFIED_CLAIM"
    HEURISTIC_FINDING = "HEURISTIC_FINDING"
    UNKNOWN_INFORMATION = "UNKNOWN_INFORMATION"


class Severity(str, Enum):
    """Standard threat and indicator severity scale."""
    INFO = "INFO"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class SourceLocation(BaseModel):
    """Location in parsed content, or an explicit reason it is unavailable."""
    source: str
    available: bool = False
    start: Optional[int] = None
    end: Optional[int] = None
    unavailable_reason: Optional[str] = None


class Observation(BaseModel):
    """A concrete parser observation separated from the rule's interpretation."""
    type: str
    value: str
    source_location: SourceLocation


class Finding(BaseModel):
    """Individual security finding with evidence and explicit technical limitations."""
    id: str
    dimension: str  # "IDENTITY", "AUTHENTICITY", "THREAT", "TRUST"
    category: FindingCategory
    severity: Severity
    title: str
    description: str
    evidence: str
    limitations: str
    # Optional for compatibility while the ledger is introduced finding type by type.
    observations: List[Observation] = Field(default_factory=list)
    review_guidance: str = ""


class ClaimedIdentitySummary(BaseModel):
    """Summary of untrusted presentation claims extracted from RFC 5322 headers."""
    display_name: str
    address: str
    domain: str
    reply_to: Optional[str] = None
    return_path: Optional[str] = None
    all_from_headers: List[str] = Field(default_factory=list)


class DimensionScore(BaseModel):
    """Structured rating for an individual security dimension."""
    level: str
    title: str
    description: str
    rationale: str
    is_simulated_or_limited: bool = False
    # Related evidence is explanatory context, not a numeric score contribution.
    related_finding_ids: List[str] = Field(default_factory=list)


class AssessmentResult(BaseModel):
    """
    The full multi-dimensional assessment result.
    Maintains strict orthogonality between identity, authenticity, threat, and trust.
    """
    incident_id: str
    evidence_hash: str
    byte_size: int
    timestamp: str
    assessment_version: str
    subject: str = Field("", description="RFC 5322 Subject line")

    # 4 Orthogonal Dimensions
    claimed_identity: ClaimedIdentitySummary
    identity_assurance: DimensionScore
    message_authenticity: DimensionScore
    threat_assessment: DimensionScore
    sender_trust: DimensionScore

    # Decision Support & Human Review
    human_review_required: bool
    human_review_reasons: List[str] = Field(default_factory=list)
    human_review_status: str = "PENDING"
    analyst_notes: str = ""

    # Structured Findings Partitioned by Category
    findings: List[Finding] = Field(default_factory=list)
    verified_facts: List[str] = Field(default_factory=list)
    unverified_claims: List[str] = Field(default_factory=list)
    heuristic_findings: List[str] = Field(default_factory=list)
    unknown_information: List[str] = Field(default_factory=list)

    # Required Safety Warning
    safety_warning: str = (
        "SAFETY MANDATE: The absence of detected threat indicators does NOT constitute proof "
        "that a message is harmless. Unknown senders are not inherently malicious, and verified "
        "senders are not inherently trustworthy."
    )
    disclaimer: str = (
        "PROTOTYPE NOTICE: This analysis was generated by a local deterministic prototype. "
        "Evidence hashes represent local integrity checks only; this system is not a certified "
        "forensic tool and does not establish a legally certified chain of custody."
    )
